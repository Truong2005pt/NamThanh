for (const lang of langs) {
  const filePath = path.join('lib', 'locales', `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace comparison
  if (COMPARISON_TRANSLATIONS[lang]) {
    const regex = /["']?comparison["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"comparison": ` + JSON.stringify(COMPARISON_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace cookie
  if (COOKIE_TRANSLATIONS[lang]) {
    const regex = /["']?cookie["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"cookie": ` + JSON.stringify(COOKIE_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace reviews
  if (REVIEWS_TRANSLATIONS[lang]) {
    const regex = /["']?reviews["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"reviews": ` + JSON.stringify(REVIEWS_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace payouts
  if (PAYOUTS_TRANSLATIONS[lang]) {
    const regex = /["']?payouts["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"payouts": ` + JSON.stringify(PAYOUTS_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated comparison, cookie, reviews, payouts in ${lang}.ts`);
}
