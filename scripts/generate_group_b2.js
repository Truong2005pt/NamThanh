const langs = ['pt', 'fr', 'de', 'it', 'pl', 'tr', 'id', 'th', 'hi', 'ru', 'ar', 'nl'];

for (const lang of langs) {
  const filePath = path.join('lib', 'locales', `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace matrix
  if (MATRIX_TRANSLATIONS[lang]) {
    const regex = /["']?matrix["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"matrix": ` + JSON.stringify(MATRIX_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace footer
  if (FOOTER_TRANSLATIONS[lang]) {
    const regex = /["']?footer["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"footer": ` + JSON.stringify(FOOTER_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated matrix, footer in ${lang}.ts`);
}

