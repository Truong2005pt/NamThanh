const langs = ['ko', 'ja', 'es', 'pt', 'fr', 'de', 'it', 'pl', 'tr', 'id', 'th', 'hi', 'ru', 'ar', 'nl'];

for (const lang of langs) {
  const filePath = path.join('lib', 'locales', `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace affiliate
  if (AFFILIATE_TRANSLATIONS[lang]) {
    const regex = /["']?affiliate["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"affiliate": ` + JSON.stringify(AFFILIATE_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace faq
  if (FAQ_TRANSLATIONS[lang]) {
    const regex = /["']?faq["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"faq": ` + JSON.stringify(FAQ_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace blog
  if (BLOG_TRANSLATIONS[lang]) {
    const regex = /["']?blog["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"blog": ` + JSON.stringify(BLOG_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace platform
  if (PLATFORM_TRANSLATIONS[lang]) {
    const regex = /["']?platform["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"platform": ` + JSON.stringify(PLATFORM_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated affiliate, faq, blog, platform in ${lang}.ts`);
}
