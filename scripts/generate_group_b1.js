const langs = ['pt', 'fr', 'de', 'it', 'pl', 'tr', 'id', 'th', 'hi', 'ru', 'ar', 'nl'];

for (const lang of langs) {
  const filePath = path.join('lib', 'locales', `${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  // Replace benefits
  if (BENEFITS_TRANSLATIONS[lang]) {
    const regex = /["']?benefits["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"benefits": ` + JSON.stringify(BENEFITS_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace steps
  if (STEPS_TRANSLATIONS[lang]) {
    const regex = /["']?steps["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"steps": ` + JSON.stringify(STEPS_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  // Replace calculator
  if (CALCULATOR_TRANSLATIONS[lang]) {
    const regex = /["']?calculator["']?\s*:\s*\{[\s\S]*?\n  \},/;
    const formatted = `"calculator": ` + JSON.stringify(CALCULATOR_TRANSLATIONS[lang], null, 4).replace(/\n/g, '\n  ') + ',';
    content = content.replace(regex, formatted);
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated benefits, steps, calculator in ${lang}.ts`);
}
