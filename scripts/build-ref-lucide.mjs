// Builds public/eracex-ref/lucide-icons.js: inline Lucide SVG icons for the concept page scripts.
// Add icon names (Lucide kebab-case) to scripts/ref-lucide-icons.json, then run: node scripts/build-ref-lucide.mjs
import fs from 'node:fs';
import path from 'node:path';

const names = JSON.parse(fs.readFileSync('scripts/ref-lucide-icons.json', 'utf8'));
const dir = 'node_modules/lucide-react/dist/esm/icons';
const map = {};
const missing = [];
for (const name of [...new Set(names)].sort()) {
  const file = path.join(dir, `${name}.mjs`);
  if (!fs.existsSync(file)) { missing.push(name); continue; }
  const src = fs.readFileSync(file, 'utf8');
  const i = src.indexOf('node:');
  if (i < 0) { missing.push(name); continue; }
  let depth = 0, j = src.indexOf('[', i), k = j;
  for (; k < src.length; k++) { if (src[k] === '[') depth++; else if (src[k] === ']') { depth--; if (depth === 0) break; } }
  const m = [null, src.slice(j, k + 1)];
  const node = Function(`return ${m[1]}`)();
  map[name] = node.map(([tag, attrs]) => {
    const { key, ...rest } = attrs; // eslint-disable-line no-unused-vars
    return [tag, rest];
  });
}
const out = `/* Generated by scripts/build-ref-lucide.mjs from lucide-react (ISC). Do not edit by hand. */
const LUCIDE=${JSON.stringify(map)};
/** lu('target', 20) -> inline <svg> string using currentColor. Unknown names return ''. */
function lu(name,size=20,extra=''){const n=LUCIDE[name];if(!n)return '';return '<svg class="lu lu-'+name+(extra?' '+extra:'')+'" xmlns="http://www.w3.org/2000/svg" width="'+size+'" height="'+size+'" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">'+n.map(([t,a])=>'<'+t+' '+Object.entries(a).map(([k,v])=>k+'="'+v+'"').join(' ')+'/>').join('')+'</svg>';}
`;
fs.writeFileSync('public/eracex-ref/lucide-icons.js', out);
console.log('icons:', Object.keys(map).length, 'missing:', missing.join(', ') || '-');
